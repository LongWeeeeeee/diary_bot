# До какой длины разрешено обрезать основу (иначе «Маше»/«Машу» не слипнутся)
MIN_STEM_LEN = 3
# Слова короче в разбор не берём вообще
MIN_WORD_LEN = 4
# Насколько основа слова должна совпасть с основой дела, чтобы считать их одним
MIN_SHARED_PREFIX = 4
MIN_PREFIX_RATIO = 0.6
# На сколько символов формы одного слова могут расходиться при склейке основ
MAX_CLUSTER_GAP = 2
# Корень короче склеивать нельзя: «ста» иначе объединяет «Стаса» и «ставки»
MIN_CLUSTER_ROOT = 4

_WORD_RE = re.compile(r"[а-яёa-z]+", re.IGNORECASE)
_SENTENCE_SPLIT = re.compile(r"[.!?…\n]+")


def normalize(word: str) -> str:
    """Приводит слово к нижнему регистру без ё."""
    return word.lower().replace("ё", "е")


def stem(word: str) -> str:
    """Грубо обрезает окончание. Не морфология, но «Маша/Маше/Машу» слипаются."""
    word = normalize(word)
    for ending in _ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= MIN_STEM_LEN:
            return word[: -len(ending)]
    return word


def activity_stems(activities: Iterable[str]) -> Set[str]:
    """Основы слов из названий дел — их из текста исключаем, чтобы не дублировать."""
    stems = set()
    for activity in activities:
        for word in _WORD_RE.findall(activity):
            if len(word) >= MIN_WORD_LEN:
                stems.add(stem(word))
    return stems


def _shared_prefix(first: str, second: str) -> int:
    length = 0
    for a, b in zip(first, second):
        if a != b:
            break
        length += 1
    return length


def is_covered(word_stem: str, known_stems: Set[str]) -> bool:
    """Уже ли это слово учтено как дело.

    Сравниваем по общему началу, а не по точному совпадению: обрезка окончаний
    грубая, и «воздержива(лся)» с «воздержан(ие)» иначе не сойдутся.
    """
    for known in known_stems:
        shared = _shared_prefix(word_stem, known)
        shortest = min(len(word_stem), len(known))
        if shared >= MIN_SHARED_PREFIX and shared >= shortest * MIN_PREFIX_RATIO:
            return True
    return False


def cluster_stems(vocabulary: Iterable[str]) -> Dict[str, str]:
    """Склеивает основы, где одна — начало другой («став» + «ставк», «энерг» + «энерги»).

    Обрезка окончаний грубая: «ставку» даёт «ставк», а «ставить» — «став»,
    и без склейки одно и то же слово считается двумя разными.
    """
    unique = sorted({s for s in vocabulary if len(s) >= MIN_STEM_LEN}, key=len)
    canonical: Dict[str, str] = {}
    for word_stem in unique:
        root = word_stem
        for candidate in unique:
            if len(candidate) >= len(word_stem):
                break
            # Разница максимум в два символа: иначе «пол» съедает «получил»,
            # а «пар» — «парней». Формы одного слова так далеко не расходятся.
            if len(candidate) < MIN_CLUSTER_ROOT:
                continue
            if len(word_stem) - len(candidate) > MAX_CLUSTER_GAP:
                continue
            if word_stem.startswith(candidate):
                root = canonical.get(candidate, candidate)
                break
        canonical[word_stem] = root
    return canonical


def _proper_name_stems(text: str) -> Set[str]:
    """Слова с заглавной буквы не в начале предложения — вероятные имена."""
    names = set()
    for sentence in _SENTENCE_SPLIT.split(text or ""):
        words = _WORD_RE.findall(sentence)
        if len(words) < 2:
            continue
        for word in words[1:]:
            if word[:1].isupper() and len(word) >= MIN_STEM_LEN:
                names.add(stem(word))
    return names


def day_terms(
    text: str, exclude: Optional[Set[str]] = None
) -> Tuple[Set[str], Dict[str, str], Set[str]]:
    """Основы слов за один день.

    Возвращает (основы, основа -> исходное слово, основы-имена).
    Каждое слово считается один раз за день, повторы внутри текста не важны.
    """
    exclude = exclude or set()
    stems: Set[str] = set()
    display: Dict[str, str] = {}
    for word in _WORD_RE.findall(text or ""):
        low = normalize(word)
        if len(low) < MIN_WORD_LEN or low in STOPWORDS or low.isdigit():
            continue
        base = stem(low)
        if len(base) < MIN_STEM_LEN or base in STOPWORDS:
            continue
        if is_covered(base, exclude):
            continue
        stems.add(base)
        # для показа берём самую короткую словоформу — она обычно начальная
        if base not in display or len(low) < len(display[base]):
            display[base] = low
    names = {n for n in _proper_name_stems(text) if not is_covered(n, exclude)}
    return stems, display, names
